 <script>
     $(document).ready(function() {
         // Outer tab hover
         $('.dropdown-menu-mega .nav-tabs > li > a[data-toggle="tab"]').hover(function() {
             $(this).tab('show');
         });

         // Inner tab hover — restricted to real tabs only now
         $('.inner-tabs .nav-tabs > li > a[data-toggle="tab"]').hover(function() {
             $(this).tab('show');
         });

         // Dholera Iconic: real link, not a tab — just clear the 3rd column on hover
         $('.real-link').hover(
             function() {
                 // Hovering Dholera Iconic: turn off Land Parcel's active look, turn this one on
                 $(this).closest('.nav-tabs-vertical').find('li.active').removeClass('active');
                 $(this).parent('li').addClass('active');

                 $(this).closest('.nested-tab-container')
                     .find('.inner-content .tab-content')
                     .stop(true, true).fadeOut(100);
             },
             function() {
                 // Leaving Dholera Iconic: restore Land Parcel as active/orange again
                 $(this).parent('li').removeClass('active');
                 $(this).closest('.nav-tabs-vertical').find('li').first().addClass('active');

                 $(this).closest('.nested-tab-container')
                     .find('.inner-content .tab-content')
                     .stop(true, true).fadeIn(100);
             }
         );
     });
 </script>

