                             document.addEventListener("DOMContentLoaded", function() {

                                 // Utility: toggle one, close siblings
                                 function toggleMenu(currentLink, submenuClass) {
                                     const submenu = currentLink.nextElementSibling;

                                     if (!submenu || !submenu.classList.contains(submenuClass)) return;

                                     // Close other open submenus at the same level
                                     const siblings = currentLink.closest('ul').querySelectorAll(`.${submenuClass}`);
                                     siblings.forEach(ul => {
                                         if (ul !== submenu) {
                                             ul.style.display = 'none';
                                         }
                                     });

                                     // Toggle current submenu
                                     submenu.style.display = submenu.style.display === 'block' ? 'none' : 'block';
                                 }

                                 // Parent toggle
                                 document.querySelectorAll('.parent_a').forEach(link => {
                                     link.addEventListener('click', function(e) {
                                         e.preventDefault();
                                         toggleMenu(this, 'child_ul');
                                     });
                                 });

                                 // Child toggle
                                 document.querySelectorAll('.child_a').forEach(link => {
                                     link.addEventListener('click', function(e) {
                                         e.preventDefault();
                                         toggleMenu(this, 'inner_ul');
                                     });
                                 });

                                 // Inner toggle
                                 document.querySelectorAll('.inner_a').forEach(link => {
                                     link.addEventListener('click', function(e) {
                                         e.preventDefault();
                                         toggleMenu(this, 'inner_child_ul');
                                     });
                                 });

                             });
                         </script>

