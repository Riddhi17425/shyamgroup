                let contactFormSubmitted = false;

                function verifyContactCaptcha(response) {
                    $("#hiddenContactRecaptcha").val(response);
                    $("#contactform").validate().element("#hiddenContactRecaptcha"); // Trigger re-validation
                }
                $(document).ready(function() {
                    // Setup form validation
                    $("#contactform").validate({
                        ignore: [],
                        rules: {
                            name: {
                                required: true,
                                blockName: true,
                                englishOnly: true,
                                minlength: 2,
                                maxlength: 50,
                                lettersonly: true
                            },
                            email: {
                                required: true,
                                email: true,
                                noSpamEmail: true,
                                englishOnly: true
                            },
                            phone: {
                                required: true,
                                validPhone: true,
                                englishOnly: true,
                                number: true,
                            },
                            subject: {
                                englishOnly: true,
                                required: true,
                                maxlength: 100
                            },
                            comment: {
                                englishOnly: true,
                                maxlength: 300
                            },
                            hiddenContactRecaptcha: {
                                required: function() {
                                    // Returns true (required) if the captcha is empty
                                    return grecaptcha.getResponse() === "";
                                }
                            }
                        },
                        messages: {
                            name: {
                                required: "Please enter your name",
                                minlength: "Name must be at least 2 characters",
                                maxlength: "Name cannot be longer than 50 characters",
                                lettersonly: "Only letters and spaces are allowed"
                            },
                            email: {
                                required: "Please enter your email",
                                email: "Please enter a valid email address",
                                noSpamEmail: "This email address is not allowed"
                            },
                            phone: {
                                required: "Please enter your phone number"
                            },
                            subject: {
                                required: "Please enter Subject",
                                maxlength: "Subject cannot be longer than 100 characters"
                            },
                            comment: {
                                maxlength: "Message cannot be longer than 300 characters"
                            },
                            hiddenContactRecaptcha: "Please complete the reCAPTCHA verification."
                        },
                        errorElement: 'div',
                        errorPlacement: function(error, element) {
                            error.addClass('invalid-feedback');
                            if (element.attr("name") === "g-recaptcha-response") {
                                error.insertAfter(".g-recaptcha"); // show error below CAPTCHA
                            } else {
                                error.insertAfter(element);
                            }
                        },
                        highlight: function(element) {
                            $(element).addClass('is-invalid').removeClass('is-valid');
                        },
                        unhighlight: function(element) {
                            $(element).addClass('is-valid').removeClass('is-invalid');
                        },
                        submitHandler: function(form) {
                            if (!contactFormSubmitted) {
                                contactFormSubmitted = true;

                                // Disable submit button and change text
                                const btn = $(form).find('input[type="submit"]');
                                if (btn.length) {
                                    btn.prop('disabled', true);
                                    btn.val('Submitting...');
                                }

                                form.submit(); // submit form normally
                            }
                        }
                    });

                });
